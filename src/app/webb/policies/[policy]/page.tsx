export function generateStaticParams() {
  return Object.keys(policyPages).map((policy) => ({ policy }));
}

export async function generateMetadata({ params }: { params: Promise<{ policy: string }> }) {
  const { policy } = await params;
  const page = policyPages[policy as keyof typeof policyPages];
  return { title: page ? `${page.title} · Study Unith` : "ไม่พบหน้า · Study Unith" };
}

export default async function PolicyPage({ params }: { params: Promise<{ policy: string }> }) {
  const { policy } = await params;
  const page = policyPages[policy as keyof typeof policyPages];
  if (!page) notFound();

  return (
    <PublicShell>
      <main className="webb-inner-page wb-policy-page">
        <div className="wb-container">
          <header className="webb-page-head">
            <div>
              <span className="webb-kicker">STUDY UNITH · ข้อมูลการใช้บริการ</span>
              <h1>{page.title}</h1>
              <p>{page.intro}</p>
            </div>
            <Link href="/webb">กลับหน้าแรก</Link>
          </header>

          <aside className="wb-policy-draft" role="note">
            <strong>ฉบับร่างสำหรับระบบสาธิต — ยังไม่ใช่ประกาศสำหรับบริการจริง</strong>
            <p>ก่อนเผยแพร่ต้องยืนยันชื่อและที่อยู่ผู้ให้บริการ ช่องทางติดต่อ รายละเอียดผู้ให้บริการภายนอก ระยะเวลาเก็บข้อมูล และการทำงานของคุกกี้ให้ตรงกับระบบจริง</p>
          </aside>

          <article className="wb-policy-content">
            {page.sections.map((section) => (
              <section key={section.heading}>
                <h2>{section.heading}</h2>
                {section.paragraphs.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
                {section.bullets && <ul>{section.bullets.map((item) => <li key={item}>{item}</li>)}</ul>}
              </section>
            ))}
            <p className="wb-policy-updated">ปรับปรุงล่าสุด 12 ตุลาคม 2569</p>
          </article>
        </div>
      </main>
    </PublicShell>
  );
}
